"""Evaluate validated upstream symbolic PK equations using JAX.

The TOML must be generated by export_symbolic_equations.jl. This module
does not fit coefficients and does not claim held-out model performance.
"""
import ast
import tomllib
from pathlib import Path

import jax
import jax.numpy as jnp

from pk_model import published_rates_to_parameters

NAMES = ("k10", "k12", "k13", "k21", "k31", "V1")
VARIABLES = ("x_age", "x_wgt", "x_bmi", "x_gdr", "x_AV")


def _evaluate(node, variables):
    """Evaluate a small arithmetic AST without Python eval or arbitrary calls."""
    if isinstance(node, ast.Expression):
        return _evaluate(node.body, variables)
    if isinstance(node, ast.Constant) and type(node.value) in (int, float):
        return jnp.asarray(node.value)
    if isinstance(node, ast.Name) and node.id in variables:
        return variables[node.id]
    if isinstance(node, ast.UnaryOp):
        value = _evaluate(node.operand, variables)
        if isinstance(node.op, ast.USub):
            return -value
        if isinstance(node.op, ast.UAdd):
            return value
    if isinstance(node, ast.BinOp):
        left = _evaluate(node.left, variables)
        right = _evaluate(node.right, variables)
        if isinstance(node.op, ast.Add):
            return left + right
        if isinstance(node.op, ast.Sub):
            return left - right
        if isinstance(node.op, ast.Mult):
            return left * right
        if isinstance(node.op, ast.Div):
            return left / right
        if isinstance(node.op, ast.Pow):
            return left ** right
    if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "abs" and len(node.args) == 1 and not node.keywords:
        return jnp.abs(_evaluate(node.args[0], variables))
    raise ValueError(f"Unsupported symbolic equation syntax: {ast.dump(node)}")



def _validate_syntax(node):
    """Check expression grammar without evaluating at arbitrary covariates."""
    if isinstance(node, ast.Expression):
        return _validate_syntax(node.body)
    if isinstance(node, ast.Constant) and type(node.value) in (int, float):
        return
    if isinstance(node, ast.Name) and node.id in VARIABLES:
        return
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.UAdd, ast.USub)):
        return _validate_syntax(node.operand)
    if isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Add, ast.Sub, ast.Mult, ast.Div, ast.Pow)):
        _validate_syntax(node.left)
        _validate_syntax(node.right)
        return
    if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "abs" and len(node.args) == 1 and not node.keywords:
        return _validate_syntax(node.args[0])
    raise ValueError(f"Unsupported symbolic equation syntax: {ast.dump(node)}")


def load_equations(path=None):
    """Load and syntax-check all six exported expressions."""
    if path is None:
        path = Path(__file__).with_name("symbolic_equations.toml")
    with open(path, "rb") as source:
        artifact = tomllib.load(source)
    if tuple(artifact["output_order"]) != NAMES:
        raise ValueError("Unexpected PK parameter order")
    equations = artifact["equations"]
    if set(equations["common"]) != set(NAMES):
        raise ValueError("Expected six common PK equations")
    for sex in ("male", "female"):
        if set(equations[sex]) != {"k13", "k31"}:
            raise ValueError("Expected sex-specific k13 and k31 equations")
    compiled = {}
    for group in ("common", "male", "female"):
        compiled[group] = {}
        for name, expression in equations[group].items():
            # Julia uses ^ for powers; Python uses **. Reject any other syntax.
            parsed = ast.parse(expression.replace("^", "**"), mode="eval")
            _validate_syntax(parsed)
            compiled[group][name] = parsed
    return compiled


def published_rates(equations, covariates):
    """Return original [k10,k12,k13,k21,k31,V1] from raw [AGE,WGT,BMI,GDR,AV].

    GDR must be -0.5 for male and +0.5 for female. All five inputs
    are raw/unstandardized, unlike the exploratory regression baseline.
    """
    age, weight, bmi, gender, av = jnp.asarray(covariates)
    variables = dict(zip(VARIABLES, (age, weight, bmi, gender, av)))
    values = []
    for name in NAMES:
        if name in ("k13", "k31"):
            # Only evaluate the selected branch. jnp.where evaluates both,
            # allowing a singular unused equation to poison gradients.
            value = jax.lax.cond(
                gender < 0,
                lambda _: _evaluate(equations["male"][name], variables),
                lambda _: _evaluate(equations["female"][name], variables),
                operand=None,
            )
        else:
            value = _evaluate(equations["common"][name], variables)
        values.append(value)
    return jnp.stack(values)


def published_parameters(equations, covariates):
    """Return solver [V1,V2,V3,CL,Q2,Q3] from raw patient covariates."""
    return published_rates_to_parameters(published_rates(equations, covariates))
